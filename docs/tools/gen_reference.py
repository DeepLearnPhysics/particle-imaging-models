#!/usr/bin/env python
"""Write the generated Reference pages of the pimm docs.

    python tools/gen_reference.py REPO_ROOT SOURCE_DIR

writes four pages under SOURCE_DIR/reference/:

* ``cli.md``: every ``pimm`` command, from its parser.
* ``recipes.md``: every config under ``configs/``, loaded with ``Config.fromfile``.
* ``api.md``: every registered component, from the registries.
* ``environment.md``: every environment variable read by ``pimm/``, ``configs/``
  and the shell scripts, found by parsing the source.

The pages are not committed. To change one, change the code it is generated from.
A file is only rewritten when its content changes, so Sphinx rebuilds stay
incremental. ``make html`` runs this before Sphinx.
"""

