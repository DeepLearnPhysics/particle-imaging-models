def cell(text: Any) -> str:
    """Make text safe for one Markdown table cell."""
    text = " ".join(str(text).split())
    return text.replace("|", "\\|") if text else "—"


def prose(text: Any) -> str:
    """Escape characters Markdown would read as HTML or emphasis, outside code spans."""
    parts = re.split(r"(`[^`]*`)", str(text or ""))
    return "".join(p if p.startswith("`") else re.sub(r"([<*])", r"\\\1", p) for p in parts)


def code(text: Any) -> str:
    text = str(text)
    fence = "``" if "`" in text else "`"
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{fence}{pad}{text}{pad}{fence}"


def table(headers: list[str], rows: Iterable[list[Any]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(cell(value) for value in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def summary(doc: str | None) -> str:
    """Return the first paragraph of a docstring as one line."""
    if not doc:
        return ""
    paragraph = inspect.cleandoc(doc).split("\n\n", 1)[0]
    return " ".join(paragraph.split())


def write(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


