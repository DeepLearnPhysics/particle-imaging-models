def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("repo_root", type=Path)
    parser.add_argument("source_dir", type=Path)
    args = parser.parse_args(argv)
    repo = args.repo_root.resolve()
    reference = args.source_dir.resolve() / "reference"
    sys.path.insert(0, str(repo))

    recipes, failures = gen_recipes(repo)
    pages = {
        "cli.md": gen_cli(repo),
        "recipes.md": recipes,
        "api.md": gen_api(repo),
        "environment.md": gen_environment(repo),
    }
    for name, text in pages.items():
        changed = write(reference / name, text.rstrip() + "\n")
        print(f"gen_reference: {'wrote' if changed else 'unchanged'} reference/{name}")
    for failure in failures:
        print(f"gen_reference: warning: recipe doesn't load: {failure}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
