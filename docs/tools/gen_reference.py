def _type(value: Any) -> str | None:
    return value.get("type") if isinstance(value, dict) else None


def gen_recipes(repo: Path) -> tuple[str, list[str]]:
    from pimm.utils.config import Config

    configs = repo / "configs"
    groups: dict[str, list[list[str]]] = defaultdict(list)
    failures: list[tuple[str, str]] = []
    for path in sorted(configs.rglob("*.py")):
        rel = path.relative_to(configs)
        if any(part.startswith("_") for part in rel.parts):
            continue
        name = rel.with_suffix("").as_posix()
        about = summary(ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))))
        try:
            cfg = Config.fromfile(str(path))
        except Exception as error:  # report, keep going
            failures.append((name, f"{type(error).__name__}: {error}".replace(str(repo) + "/", "")))
            continue
        model = cfg.get("model", {})
        backbone = model.get("backbone") if isinstance(model, dict) else None
        model_text = " · ".join(code(t) for t in (_type(model), _type(backbone)) if t)
        data = cfg.get("data", {})
        train = data.get("train", {}) if isinstance(data, dict) else {}
        data_text = code(_type(train)) if _type(train) else ""
        if isinstance(train, dict) and train.get("revision"):
            data_text += f" {train['revision']}"
        weight = cfg.get("weight")
        groups[rel.parent.as_posix()].append(
            [
                code(name),
                prose(about),
                model_text,
                data_text,
                code(weight) if weight else "",
                cfg.get("epoch", ""),
                cfg.get("batch_size", ""),
            ]
        )

    count = sum(len(rows) for rows in groups.values())
    out = [HEADER, "# Recipe catalog\n"]
    out.append(
        f"pimm ships {count} recipes. A recipe is a config under `configs/`; pass its name to "
        "`--train.config`. `uv run pimm ls` prints the same names. Batch size counts events per "
        "step across all GPUs. A blank warm start means the recipe starts from random weights "
        "unless you pass `--train.weight`.\n"
    )
    for group in sorted(groups):
        out.append(f"## {group}\n")
        out.append(
            table(
                ["Recipe", "About", "Model", "Data", "Warm start", "Epochs", "Batch size"],
                groups[group],
            )
        )
    if failures:
        out.append("## Recipes that don't load\n")
        out.append(
            "These configs fail in `Config.fromfile`, so neither the catalog nor the launcher can use them.\n"
        )
        out.append(table(["Recipe", "Error"], [[code(n), e] for n, e in failures]))
    return "\n".join(out), [f"{n}: {e}" for n, e in failures]


