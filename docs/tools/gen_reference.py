def gen_api(repo: Path) -> str:
    for package in ("pimm.models", "pimm.datasets", "pimm.engines.hooks"):
        importlib.import_module(package)

    out = [HEADER, "# Python API\n"]
    out.append(
        "Each component in a config is a dict whose `type` is a name registered here; pimm builds "
        "the class with the dict's other keys. Summaries are the first paragraph of each class's "
        "docstring. To add a name, see [Add a component](../develop/add-component.md).\n"
    )
    sections = []
    for heading, module_name, attribute, used in REGISTRIES:
        registry = getattr(importlib.import_module(module_name), attribute)
        items = registry.module_dict
        if not items:
            continue
        rows = []
        for name in sorted(items, key=str.lower):
            cls = items[name]
            rows.append(
                [
                    code(name),
                    code(f"{cls.__module__}.{cls.__qualname__}"),
                    prose(summary(cls.__dict__.get("__doc__"))),
                ]
            )
        sections.append((heading, len(items), used, rows))

    out.append(
        table(
            ["Registry", "Names", "Used for"],
            [[f"[{h}](#{h.lower()})", n, u] for h, n, u, _ in sections],
        )
    )
    for heading, _, _, rows in sections:
        out.append(f"## {heading}\n")
        out.append(table(["Name", "Class", "Summary"], rows))
    return "\n".join(out)


