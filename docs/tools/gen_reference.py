def _first_sentence(text: str) -> str:
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    return match.group(1) if match else text


def _comment(lines: list[str], lineno: int, name: str) -> str:
    """Return the comment that describes a read, or "".

    That is the comment on the same line, or the comment block right above it when
    the block is at most two lines or names the variable. Only its first sentence
    is kept.
    """
    line = lines[lineno - 1]
    if "#" in line and not line.lstrip().startswith("#"):
        trailing = line.split("#", 1)[1].strip()
        if trailing and not trailing.startswith(("noqa", "type:", "pragma")):
            return _first_sentence(trailing)
    block = []
    index = lineno - 2
    while index >= 0 and lines[index].lstrip().startswith("#"):
        block.insert(0, lines[index].strip().lstrip("#").strip())
        index -= 1
    block = [part for part in block if part and not set(part) <= set("─-=#")]
    stem = name.split("<", 1)[0]
    if not block or (len(block) > 2 and stem not in " ".join(block)):
        return ""
    return _first_sentence(" ".join(block))


class _EnvVisitor(ast.NodeVisitor):
    def __init__(self, constants: dict[str, str]):
        self.constants = constants
        self.scopes: list[ast.AST] = []
        self.loops: dict[str, list[str]] = {}
        self.found: list[tuple[str, int, str, str | None]] = []

    @staticmethod
    def _is_environ(node: ast.AST) -> bool:
        return (
            isinstance(node, ast.Attribute)
            and node.attr == "environ"
            and isinstance(node.value, ast.Name)
            and node.value.id == "os"
        )

    def _where(self) -> str:
        names = [
            s.name
            for s in self.scopes
            if isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
        ]
        return ".".join(names) or "module"

    def _local_value(self, name: str) -> ast.AST | None:
        for scope in reversed(self.scopes):
            for node in ast.walk(scope):
                if isinstance(node, ast.Assign) and any(
                    isinstance(t, ast.Name) and t.id == name for t in node.targets
                ):
                    return node.value
        return None

    def _names(self, node: ast.AST) -> list[str]:
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            return [node.value]
        if isinstance(node, ast.Name):
            value = self._local_value(node.id)
            if value is not None:
                return self._names(value)
            if node.id in self.constants:
                return [self.constants[node.id]]
            return []
        if isinstance(node, ast.JoinedStr):
            variants = [""]
            for part in node.values:
                if isinstance(part, ast.Constant):
                    variants = [v + str(part.value) for v in variants]
                    continue
                expr = part.value
                base = (
                    expr.func.value
                    if (
                        isinstance(expr, ast.Call)
                        and isinstance(expr.func, ast.Attribute)
                        and expr.func.attr == "upper"
                    )
                    else expr
                )
                choices = self.loops.get(base.id) if isinstance(base, ast.Name) else None
                if choices:
                    variants = [v + c.upper() for v in variants for c in choices]
                else:
                    label = base.id if isinstance(base, ast.Name) else ast.unparse(base)
                    variants = [v + f"<{label.upper()}>" for v in variants]
            return variants
        return []

    def _record(self, node: ast.AST, key: ast.AST, default: ast.AST | None = None) -> None:
        text = None
        if default is not None:
            try:
                value = ast.literal_eval(default)
                text = None if value is None else (value if isinstance(value, str) else repr(value))
            except ValueError:
                text = None
        for name in self._names(key):
            self.found.append((name, node.lineno, self._where(), text))

    def visit_FunctionDef(self, node):
        self.scopes.append(node)
        self.generic_visit(node)
        self.scopes.pop()

    visit_AsyncFunctionDef = visit_FunctionDef
    visit_ClassDef = visit_FunctionDef

    def visit_For(self, node):
        if isinstance(node.target, ast.Name) and isinstance(node.iter, (ast.Tuple, ast.List)):
            values = [
                e.value
                for e in node.iter.elts
                if isinstance(e, ast.Constant) and isinstance(e.value, str)
            ]
            if len(values) == len(node.iter.elts):
                self.loops[node.target.id] = values
        self.generic_visit(node)
        if isinstance(node.target, ast.Name):
            self.loops.pop(node.target.id, None)

    def visit_Call(self, node):
        func = node.func
        if node.args and isinstance(func, ast.Attribute):
            default = node.args[1] if len(node.args) > 1 else None
            if func.attr in ("get", "setdefault", "pop") and self._is_environ(func.value):
                self._record(node, node.args[0], default)
            elif (
                func.attr == "getenv" and isinstance(func.value, ast.Name) and func.value.id == "os"
            ):
                self._record(node, node.args[0], default)
        self.generic_visit(node)

    def visit_Subscript(self, node):
        if self._is_environ(node.value) and isinstance(node.ctx, ast.Load):
            self._record(node, node.slice)
        self.generic_visit(node)

    def visit_Compare(self, node):
        if (
            len(node.ops) == 1
            and isinstance(node.ops[0], (ast.In, ast.NotIn))
            and self._is_environ(node.comparators[0])
        ):
            self._record(node, node.left)
        self.generic_visit(node)


def _module_constants(files: list[Path]) -> dict[str, str]:
    """Module-level ``NAME = "string"`` assignments; names bound twice are dropped."""
    seen: dict[str, set[str]] = defaultdict(set)
    for path in files:
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        for node in tree.body:
            if (
                isinstance(node, ast.Assign)
                and isinstance(node.value, ast.Constant)
                and isinstance(node.value.value, str)
            ):
                for target in node.targets:
                    if isinstance(target, ast.Name):
                        seen[target.id].add(node.value.value)
    return {name: values.pop() for name, values in seen.items() if len(values) == 1}


_SH_DEFAULTED = re.compile(r"\$\{([A-Z][A-Z0-9_]*):?[-=]([^}$]*)\}")
_SH_READ = re.compile(r"\$\{?([A-Z][A-Z0-9_]*)")
_SH_ASSIGN = re.compile(r"(?:^|[\s;&|(])(?:export\s+|local\s+|readonly\s+)?([A-Z][A-Z0-9_]*)=")
_SH_BIND = re.compile(r"\b(?:read(?:\s+-\w+)*|for|getopts\s+\S+)\s+([A-Z][A-Z0-9_]*)")


def _shell_reads(path: Path) -> list[tuple[str, int, str | None]]:
    """Variables a script reads from its environment.

    A variable counts when it is expanded with a default (``${X:-...}``), or when it
    is expanded but never assigned in the script.
    """
    lines = path.read_text(encoding="utf-8").splitlines()
    assigned: set[str] = set()
    for line in lines:
        if line.lstrip().startswith("#"):
            continue
        assigned.update(_SH_ASSIGN.findall(line))
        assigned.update(_SH_BIND.findall(line))
    found: dict[str, int] = {}
    defaults: dict[str, str] = {}
    in_heredoc = None
    for lineno, line in enumerate(lines, 1):
        if in_heredoc:
            if line.strip() == in_heredoc:
                in_heredoc = None
            continue
        heredoc = re.search(r"<<-?\s*'([A-Z]+)'", line)
        if heredoc:
            in_heredoc = heredoc.group(1)
        if line.lstrip().startswith("#"):
            continue
        for name, default in _SH_DEFAULTED.findall(line):
            found.setdefault(name, lineno)
            if default:
                defaults.setdefault(name, default)
        for name in _SH_READ.findall(line):
            if name not in assigned:
                found.setdefault(name, lineno)
    return [(n, l, defaults.get(n)) for n, l in found.items() if n not in SHELL_IGNORE]


def collect_env(repo: Path) -> dict[str, EnvVar]:
    py_files = sorted(
        p
        for root in ("pimm", "configs")
        for p in (repo / root).rglob("*.py")
        if "__pycache__" not in p.parts
    )
    constants = _module_constants([p for p in py_files if p.is_relative_to(repo / "pimm")])
    found: dict[str, EnvVar] = {}

    def add(
        name: str, rel: str, lineno: int, where: str, default: str | None, lines: list[str]
    ) -> None:
        var = found.setdefault(name, EnvVar(name))
        var.reads.append(EnvRead(rel, lineno, where, _comment(lines, lineno, name), default))

    for path in py_files:
        text = path.read_text(encoding="utf-8")
        try:
            tree = ast.parse(text)
        except SyntaxError:
            continue
        visitor = _EnvVisitor(constants)
        visitor.visit(tree)
        lines = text.splitlines()
        rel = path.relative_to(repo).as_posix()
        for name, lineno, where, default in visitor.found:
            add(name, rel, lineno, where, default, lines)

    shell_files = sorted((repo / "scripts").rglob("*.sh")) + sorted((repo / "pimm").rglob("*.sh"))
    for path in shell_files:
        lines = path.read_text(encoding="utf-8").splitlines()
        rel = path.relative_to(repo).as_posix()
        for name, lineno, default in _shell_reads(path):
            add(name, rel, lineno, "script", default, lines)
    return found


def _area(path: str) -> int:
    for index, (_, prefixes) in enumerate(AREAS):
        if path.startswith(prefixes):
            return index
    return len(AREAS)


def gen_environment(repo: Path) -> str:
    variables = collect_env(repo)
    by_area: dict[int, list[EnvVar]] = defaultdict(list)
    for var in variables.values():
        by_area[min(_area(r.path) for r in var.reads)].append(var)

    out = [HEADER, "# Environment variables\n"]
    out.append(
        f"pimm reads these {len(variables)} variables. `scripts/train.sh` first sources a `.env` "
        "file at the repository root, so assignments there reach every training process. "
        "`<NAME>` stands for part of a variable name filled in at run time, such as a dataset "
        "revision. A default is the value the code falls back to when the variable is unset. "
        "Libraries pimm uses, such as PyTorch, W&B and the Hugging Face Hub, read their "
        "own variables, which aren't listed.\n"
    )
    headings = [h for h, _ in AREAS] + ["Other"]
    for index in sorted(by_area):
        out.append(f"## {headings[index]}\n")
        rows = []
        for var in sorted(by_area[index], key=lambda v: v.name):
            places = []
            for read in var.reads:
                place = (
                    read.path
                    if read.where in ("module", "script")
                    else f"{read.path} ({read.where})"
                )
                if place not in places:
                    places.append(place)
            notes = list(dict.fromkeys(read.note for read in var.reads if read.note))[:2]
            defaults = list(dict.fromkeys(read.default for read in var.reads if read.default))
            rows.append(
                [
                    code(var.name),
                    ", ".join(code(d) for d in defaults),
                    ", ".join(code(p) for p in places),
                    prose(" ".join(notes)),
                ]
            )
        out.append(table(["Variable", "Default", "Read in", "Note in the code"], rows))
    return "\n".join(out)


