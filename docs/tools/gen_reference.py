class _Captured(Exception):
    def __init__(self, parser: argparse.ArgumentParser):
        self.parser = parser


def capture_parser(entry: Callable[[list[str]], Any]) -> argparse.ArgumentParser:
    """Run an argparse entry point until it parses, and return its parser."""

    def parse_args(self, *args, **kwargs):
        raise _Captured(self)

    original = argparse.ArgumentParser.parse_args
    argparse.ArgumentParser.parse_args = parse_args
    try:
        entry([])
    except _Captured as captured:
        return captured.parser
    finally:
        argparse.ArgumentParser.parse_args = original
    raise RuntimeError(f"{entry.__module__}.{entry.__name__} did not build a parser")


_DEFAULT_RE = re.compile(r"\s*\(default: (.*)\)\s*$", re.S)


def split_default(help_text: str | None) -> tuple[str, str | None]:
    """Split tyro's trailing ``(default: X)`` off a help string."""
    help_text = (help_text or "").replace("%%", "%")
    match = _DEFAULT_RE.search(help_text)
    if not match:
        return help_text.strip(), None
    return help_text[: match.start()].strip(), match.group(1)


def flag_name(action: argparse.Action) -> str:
    return " / ".join(code(option) for option in action.option_strings)


def argument_rows(parser: argparse.ArgumentParser) -> list[list[str]]:
    rows = []
    for action in parser._actions:
        if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        if action.help == argparse.SUPPRESS:
            continue
        help_text, default = split_default(action.help)
        if action.option_strings:
            name = flag_name(action)
            if default is None and action.default not in (None, False, argparse.SUPPRESS):
                default = action.default
        else:
            name = code(action.metavar or action.dest.upper())
            if action.nargs == "?" and action.default is not None:
                default = action.default
        rows.append([name, prose(help_text), code(default) if default not in (None, "") else ""])
    return rows


def render_argparse(parser: argparse.ArgumentParser, prog: str, level: int) -> str:
    parser.prog = prog
    out = []
    description = summary(parser.description)
    if description:
        out.append(prose(description[:1].upper() + description[1:]) + "\n")
    usage = parser.format_usage().strip()
    out.append(f"```text\n{usage}\n```\n")
    rows = argument_rows(parser)
    if rows:
        out.append(table(["Argument", "Meaning", "Default"], rows))
    for action in parser._actions:
        if not isinstance(action, argparse._SubParsersAction):
            continue
        helps = {choice.dest: choice.help for choice in action._choices_actions}
        for name, sub in action.choices.items():
            out.append(f"{'#' * level} `{prog} {name}`\n")
            if helps.get(name):
                sub.description = sub.description or helps[name]
            out.append(render_argparse(sub, f"{prog} {name}", level + 1))
    return "\n".join(out)


def tyro_parser(command_type: type, site: str) -> argparse.ArgumentParser:
    import tyro.extras

    from pimm.launch.config import load_config
    from pimm.launch.schema import LaunchConfig

    base = load_config(site=site, recipe=None, launch_timestamp="")
    default = command_type.from_config(LaunchConfig.from_dict(base))
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", DeprecationWarning)
        return tyro.extras.get_parser(command_type, default=default)


def tidy_metavar(metavar: str) -> str:
    """Turn tyro metavars such as ``{None}|STR`` into ``str``, ``[STR [STR ...]]`` into ``str ...``."""
    if metavar.startswith("[") and metavar.endswith("...]]"):
        return tidy_metavar(metavar[1:].split(" ", 1)[0]) + " ..."
    parts = [part for part in metavar.split("|") if part != "{None}"]
    return " | ".join(part if part.startswith("{") else part.lower() for part in parts)


def tyro_groups(parser: argparse.ArgumentParser) -> list[tuple[str, str, list[list[str]]]]:
    groups = []
    for group in parser._action_groups:
        rows = []
        for action in group._group_actions:
            if action.dest == "help" or action.help == argparse.SUPPRESS:
                continue
            help_text, default = split_default(action.help)
            metavar = tidy_metavar(action.metavar) if isinstance(action.metavar, str) else "bool"
            rows.append(
                [
                    flag_name(action),
                    code(metavar),
                    prose(help_text),
                    code(default) if default not in (None, "") else "",
                ]
            )
        if rows:
            groups.append((group.title or "", summary(group.description), rows))
    return groups


def keyword_literal(path: Path, function: str, keyword: str) -> Any:
    """Return a literal keyword argument passed inside ``function`` in ``path``."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name == function:
            for call in ast.walk(node):
                if isinstance(call, ast.Call):
                    for kw in call.keywords:
                        if kw.arg == keyword:
                            return ast.literal_eval(kw.value)
    return None


def gen_cli(repo: Path) -> str:
    from pimm.cli import export, launch, main, submit, trace, watchdog
    from pimm.launch.schema import LaunchCommand, SubmitCommand

    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        main.main(["--help"])
    commands = []
    listing = buffer.getvalue().split("commands:", 1)[1]
    for line in listing.strip().splitlines():
        name, _, text = line.strip().partition(" ")
        commands.append((name, text.strip()))

    out = [HEADER, "# Command line\n"]
    out.append(
        "`pimm` is installed with the package. Run it from the checkout as `uv run pimm <command>`; "
        "every command takes `-h`.\n"
    )
    out.append(table(["Command", "Does"], [[f"[`pimm {n}`](#pimm-{n})", t] for n, t in commands]))

    sections: dict[str, str] = {}
    sections["ls"] = (
        f"{summary(main.list_configs.__doc__)} The names are paths under `configs/` without `.py`, "
        "the form `--train.config` takes.\n\n```text\nusage: pimm ls [DIRECTORY ...]\n```\n"
    )

    launch_parser = tyro_parser(LaunchCommand, site="local")
    text = [summary(launch.__doc__) + "\n"]
    text.append(
        "```text\nusage: pimm launch [FLAGS] [-- KEY=VALUE ...]\n```\n\n"
        "Flags set the launch config; `KEY=VALUE` tokens after a bare `--` override the experiment "
        "config (see [Configs and overrides](../training/configs.md)). Defaults below come from "
        "`launch/defaults.yaml` and the `local` site profile; `--site` and `--recipe` load others.\n"
    )
    for title, description, rows in tyro_groups(launch_parser):
        heading = "General" if title == "options" else f"`--{title.removesuffix(' options')}.*`"
        text.append(f"### {heading}\n")
        if description:
            text.append(description + "\n")
        text.append(table(["Flag", "Type", "Meaning", "Default"], rows))
    sections["launch"] = "\n".join(text)

    launch_flags = {a.dest for a in launch_parser._actions}
    submit_parser = tyro_parser(SubmitCommand, site="local")
    extra = [a for a in submit_parser._actions if a.dest not in launch_flags]
    default_site = keyword_literal(Path(submit.__file__), "parse_command", "default_site")
    text = [summary(submit.__doc__) + "\n"]
    text.append(
        "```text\nusage: pimm submit [FLAGS] [-- KEY=VALUE ...]\n```\n\n"
        "`pimm submit` takes every [`pimm launch`](#pimm-launch) flag"
        + (f", with `--site` defaulting to `{default_site}`" if default_site else "")
        + ", plus:\n"
    )
    rows = []
    for action in extra:
        help_text, default = split_default(action.help)
        rows.append([flag_name(action), prose(help_text), code(default) if default else ""])
    text.append(table(["Flag", "Meaning", "Default"], rows))
    sections["submit"] = "\n".join(text)

    for name, module in (("watchdog", watchdog), ("trace", trace), ("export", export)):
        entry = getattr(module, "parse_args", None) or module.main
        parser = capture_parser(entry)
        parser.description = parser.description or module.__doc__
        sections[name] = render_argparse(parser, f"pimm {name}", level=3)

    for name, _ in commands:
        out.append(f"## `pimm {name}`\n")
        if name not in sections:
            raise RuntimeError(f"no reference section for `pimm {name}`")
        out.append(sections.get(name, "") or "")
    return "\n".join(out)


